def _inversion_recovery(pool: ParameterPool) -> ResolvedTag | None:
    value = pool.get("RFR_SERIES_PIIM_MR_SERIES_SEL_PART_INVERSION_RECOVERY")
    if not isinstance(value, str) or not value:
        return None
    return ResolvedTag(0x0018, 0x9009, "CS", "NO" if value.strip().upper() == "N" else "YES")


def _spatial_presaturation(pool: ParameterPool) -> ResolvedTag | None:
    value = pool.get("RFR_SERIES_PIIM_MR_SPATIAL_PRESATURATION")
    if not isinstance(value, str) or not value:
        return None
    return ResolvedTag(0x0018, 0x9027, "CS", "NONE" if value.strip().upper() == "N" else "SLAB")


def old_format_tags(pool: ParameterPool) -> list[ResolvedTag]:
    """Resolve every old-format (REL5/REL53) tag this pool has data for.

    Mirrors ``new_format_tags``'s shape and exclusions (VR resolution via
    ``resolve_vr``, value coercion via ``coerce_value``,
    ``ALWAYS_EXCLUDED_TAGS`` skipped -- see new_format.py for why those
    specific tags are always parrec2dcm's own call, never a raw DB
    snapshot) but drives its own extracted table instead of parsing
    ``tag_<hex8>``-shaped names.
    """
    resolved: list[ResolvedTag] = []
    for group, element, names in _OLD_FORMAT_ENTRIES:
        if (group, element) in ALWAYS_EXCLUDED_TAGS:
            continue
        raw_values = [pool.get(name) for name in names]
        if any(v is None for v in raw_values):
            continue
        record = pool.get_record(names[0]) or {}
        vr = resolve_vr(group, element, record)
        if vr is None:
            continue
        value = coerce_value(vr, raw_values[0] if len(raw_values) == 1 else raw_values)
        if value is None:
            continue
        resolved.append(ResolvedTag(group, element, vr, value))

    for special in (_inversion_recovery, _spatial_presaturation):
        tag = special(pool)
        if tag is not None:
            resolved.append(tag)

    return resolved
