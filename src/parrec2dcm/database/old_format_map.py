"""Old-format (REL5/REL53) Philips database parameter -> DICOM tag mapping.

Mechanically extracted from ``DICOMExporter.m`` lines 1400-1929 (the
``elseif (strcmpi(D.mRelease(1:4), 'REL5'))`` branch -- REL5 and REL53
share this single table; the branch's own REL53-specific sub-case, lines
1848-1854, only affects two minor private tags, see below) using a
disposable, unshipped extraction script: regex-matched both call shapes
the source uses --

    vCurPar = {'0xGGGG', '0xEEEE'};
        D.set_par(vCurPar, D.get_db_value('NAME'[, true]), 'static');
    vCurPar = 'KeywordName';
        D.set_par(vCurPar, D.get_db_value('NAME'[, true]), 'static');

(and their multi-name, ``D.get_db_value({'A','B',...})``, variants) --
resolving keyword-form targets to (group, element) via pydicom's own
dictionary. Verified complete: matched 481 of 485 active (non-commented)
``set_par`` calls in the range -- 480 landed in the mechanical table
below (478 remain after dropping 2, see below), the remaining 4 are
derived-value special cases the extractor deliberately doesn't match
(``StudyID``/``IntervalsAcquired``/``InversionRecovery``/
``SpatialPresaturation``, discussed below). Spot-checked 20 random
entries by hand against the source lines, and cross-checked the matched
count against a raw grep count of ``set_par(`` calls in the range.

Not ported, deliberately:

- The ``as_string`` third argument to ``get_db_value`` (a crude
  numeric-vs-string type guess) -- this package's VR-based
  ``coerce_value`` (new_format.py) already coerces every value correctly
  from its real VR, making that guess redundant.
- ``StudyID``'s MATLAB-``datenum``-derived numeric encoding (a short
  mnemonic ID, not an identifier anything depends on for correctness) --
  ``dataset_builder.py`` already sets a reasonable equivalent
  (``StudyInstanceUID[-16:]``) from static tags, applied before this
  module's tags in the merge order, so simply not overriding it here
  reproduces the same "last 16 chars" fallback the MATLAB source itself
  falls back to whenever its own date-parsing attempt fails.
- ``IntervalsAcquired``'s "take the first element of ``VW_rr_intervals``"
  special case -- a plain mechanical entry for the same DICOM tag,
  sourced from ``RFR_FOREIGN_DICOM_INTERVALS_ACQUIRED``, is already in
  the table below (from earlier in the source file) and serves as a
  reasonable equivalent without needing to replicate MATLAB's array
  indexing against a JSON value of uncertain shape.
- The non-REL53 (``else``) sub-branch for private tags (2005,101E)/
  (2005,101F), sourced from ``UGN1_PV_mip_protocol``/
  ``UGN1_PV_mpr_protocol`` -- legacy ``UGN_``-prefixed goal-parameter
  naming is out of scope entirely (per the project plan), so only the
  REL53 sub-branch's ``VAL01_``-prefixed source is kept. Note that the
  REL53 sub-branch itself maps *both* tags from
  ``VAL01_PV_mip_protocol`` (source lines 1849-1850) -- looks like a
  copy-paste bug in the original (mip_protocol repeated where
  mpr_protocol would be expected), but is preserved as-is rather than
  guessed at, since a real ``VAL01_PV_mpr_protocol`` parameter's
  existence/naming isn't independently confirmed.
- One confirmed copy-paste bug dropped outright (not merely
  deprioritized like the above): source line 1919 reuses ``vCurPar =
  'InversionTimes'`` from the line above instead of updating it, so
  ``RFR_SERIES_PIIM_MR_SERIES_NR_OF_CHEMICAL_SHIFTS`` (a dynamic-scan
  count) would silently overwrite the real ``InversionTimes`` value --
  clearly wrong regardless of MATLAB fidelity, so it's excluded rather
  than ported.

``InversionRecovery`` and ``SpatialPresaturation`` (the two remaining
special cases, source lines 1926-1929) *are* ported (see
``_inversion_recovery``/``_spatial_presaturation`` below): simple,
unambiguous Y/N-style derivations with no cross-language numeric-format
risk.

Entries are applied in the *same order* as the source file: later
entries for the same (group, element) legitimately override earlier ones
(matching a cascading EXAM -> IMAGE -> SERIES -> ECSERIES override
pattern already present in the original), and ``old_format_tags``
preserves that ordering so ``dataset_builder.py``'s sequential
``add_new`` calls apply it identically. A failed/missing lookup simply
doesn't append an entry, leaving whatever an earlier successful entry
for that address already set untouched -- exactly matching ``set_par``'s
own "silently no-op on NaN/unresolvable" behavior (DICOMExporter.m,
``set_par``, 2497-2556).
"""

