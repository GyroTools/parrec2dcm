"""Local table of Philips private DICOM tags used by parrec2dcm.

Mechanically extracted from the Philips private-tag dictionary in the
`gtpackn-go` project's `internal/db/dcmdict.go` (itself derived from the
same "Copyright 2000-2007 The MathWorks, Inc." lineage as the legacy
MATLAB exporter's `MRdict.txt`) -- 514 entries across groups 0x0019,
0x0021, 0x1001, 0x2001, 0x2005. That source gives tag/VR/keyword but not
real private-creator ID strings (only generic placeholders); the actual
well-known Philips creator strings for the blocks we can confidently
attribute ("Philips Imaging DD 001", "Philips MR Imaging DD 001"-"005")
come from the legacy MATLAB exporter itself (`DICOMExporter.m`, where they
are written verbatim as private-creator element values). Entries outside
those known blocks (group 0x0019/0x0021/0x1001, and a handful of
higher-numbered blocks in 0x2001/0x2005) have no confirmed creator string
-- ``creator=None`` for those, and `set_private_tag` writes them directly
without declaring a private block (still valid, readable Explicit-VR
DICOM; just without the "nice" creator-block registration some tools use
for pretty-printing unrecognized private tags).

Kept as a local/scoped table rather than being registered globally into
``pydicom.datadict`` -- see the module docstring on ``set_private_tag`` for
why.
"""

