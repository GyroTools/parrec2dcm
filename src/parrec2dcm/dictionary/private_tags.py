def set_private_tag(ds: Dataset, name: str, value: object) -> None:
    """Write a Philips private tag by its dictionary keyword.

    No-ops silently if ``value`` is ``None``, mirroring the legacy
    exporter's ``set_par``, which drops tags with no value rather than
    writing an empty/invalid one.

    When the tag's creator is unknown (``PrivateTag.creator is None``),
    writes the tag directly with an explicit VR instead of declaring a
    private block -- still valid, readable DICOM, just without a
    registered creator for tools that specifically look one up.
    """
    if value is None:
        return
    tag = PRIVATE_TAGS[name]
    if tag.creator is None:
        ds.add_new((tag.group, tag.element), tag.vr, value)
        return
    block = ds.private_block(tag.group, tag.creator, create=True)
    block.add_new(tag.block_offset, tag.vr, value)
